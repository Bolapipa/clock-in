export const TEXTOS: Record<Lingua, Dicionario> = { pt, en };

// Data AAAA-MM-DD no formato de cada língua (26/10/2026 ou Oct 26, 2026)
export function dataNaLingua(data: string, lingua: Lingua): string {
  const [ano, mes, dia] = data.split("-").map(Number);
  if (!ano || !mes || !dia) return data;
  return new Date(Date.UTC(ano, mes - 1, dia)).toLocaleDateString(TEXTOS[lingua].localidade, { timeZone: "UTC", day: "2-digit", month: lingua === "pt" ? "2-digit" : "short", year: "numeric" });
}
